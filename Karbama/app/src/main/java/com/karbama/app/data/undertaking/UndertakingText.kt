package com.karbama.app.data.undertaking

/**
 * متن رسمی تعهدنامه — زبان اصلی این سند فارسی است (مثل نسخه‌ی چاپی و امضاشده).
 * عنوان‌ها و برچسب‌های هر زبان از فایل ui/i18n/Strings.kt می‌آید و متن بندها
 * همیشه به فارسی نمایش داده می‌شود تا متن حقوقی دست‌نخورده بماند.
 */
object UndertakingText {

    /**
     * بندهای تعهدنامه. مقدارهای داخل آکولاد با داده‌های واقعی پر می‌شوند:
     * {name} {father} {nationalId} {fee}
     */
    val CLAUSES: List<String> = listOf(
        "اینجانب {name} فرزند {father} به شماره ملی {nationalId} با آگاهی کامل از شرایط و ضوابط اقرار و تأیید می‌نمایم که " +
            "مبلغ {fee} را بابت هزینه خدمات کارگزار، مشاوره، پشتیبانی و معرفی به کارفرما یا پیمانکار پرداخت نموده‌ام.",

        "اینجانب آگاه هستم که وظیفه کارگزار صرفاً معرفی اینجانب به کارفرما، پیمانکار یا فرصت شغلی مورد درخواست بوده و " +
            "کارگزار هیچ‌گونه تعهد یا مسئولیتی در قبال استخدام قطعی، میزان حقوق و مزایا، شرایط کار، مدت همکاری، اسکان، " +
            "بیمه، اقامت، مجوز کار یا سایر توافقات احتمالی میان اینجانب و کارفرما یا پیمانکار نخواهد داشت.",

        "همچنین تأیید می‌نمایم که پس از انجام معرفی توسط کارگزار، خدمات موضوع این تعهدنامه انجام‌شده تلقی گردیده و " +
            "مبلغ پرداختی به عنوان تسویه حساب کامل هزینه خدمات کارگزار محسوب می‌شود.",

        "اینجانب اقرار می‌نمایم که مبلغ پرداختی فوق تحت هیچ شرایطی قابل استرداد، مطالبه، عودت یا بازگشت نبوده و " +
            "حق هرگونه ادعا، اعتراض در تمامی مراجع قضایی و یا مطالبه وجه پرداختی را از خود سلب و ساقط می‌نمایم.",

        "این تعهدنامه با رضایت کامل، آگاهی از مفاد آن و بدون هیچ‌گونه اجبار یا اکراه تنظیم و امضا گردیده و برای اینجانب لازم‌الاجرا می‌باشد."
    )

    /** پر کردن جاهای خالی بندها */
    fun clauses(name: String, father: String, nationalId: String, feeText: String): List<String> =
        CLAUSES.map { clause ->
            clause
                .replace("{name}", name)
                .replace("{father}", father)
                .replace("{nationalId}", nationalId)
                .replace("{fee}", feeText)
        }
}

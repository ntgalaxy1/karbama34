/**
 * چندزبانه: فارسی، ترکی استانبولی، انگلیسی.
 * برای اضافه‌کردن یک متن جدید کافی است در هر سه دیکشنری یک کلید بگذاری.
 */
class Loc(val code: String) {

    private val map: Map<String, String> = DICTS[code] ?: DICTS.getValue("fa")

    val rtl: Boolean get() = code == "fa" || code == "ar"   // #28: عربی هم راست‌به‌چپ

    operator fun get(key: String): String = map[key] ?: DICTS.getValue("fa")[key] ?: key

    /** متن با جای‌گذار: f("step_of", "۱", "۳") */
    fun f(key: String, vararg args: String): String {
        var s = this[key]
        args.forEachIndexed { i, a -> s = s.replace("{$i}", a) }
        return s
    }

    /** تبدیل ارقام لاتین به ارقام فارسی (در حالت فارسی) */
    fun digits(text: String): String = if (code != LANG_FA) text else buildString {
        text.forEach { c -> append(if (c in '0'..'9') FA_DIGITS[c - '0'] else c) }
    }

    /** رقم‌ها را در فارسی به شکل ۱۲۳ نشان می‌دهد */
    fun n(value: Number): String = digits(value.toString())

    /** ۲۵٬۰۰۰ ₺ */
    fun money(v: Long): String = digits("%,d".format(v).replace(',', '.')) + " ₺"

    fun jobTitle(key: String): String = Catalog.titleName(key, code)

    fun jobIcon(key: String): String = Catalog.titleIcon(key)

    fun contract(key: String): String = this["ct_$key"]

    fun condition(key: String): String = this["cond_$key"]

    fun status(key: String): String = when (key) {
        "reviewed" -> this["st_reviewed"]
        "referred" -> this["st_referred"]
        else -> this["st_new"]
    }

    /** ۰ تا ۵ بر اساس درصد تسلط */
    fun levelBand(percent: Int): String = this["lv${(percent / 20).coerceIn(0, 5)}"]

    fun timeAgo(ts: Long): String {
        if (ts <= 0L) return this["unknown"]
        val diff = System.currentTimeMillis() - ts
        val min = diff / 60000
        val hour = diff / 3_600_000
        val day = diff / 86_400_000
        return when {
            min < 1 -> this["just_now"]
            min < 60 -> this.f("min_ago", n(min))
            hour < 24 -> this.f("h_ago", n(hour))
            day < 30 -> this.f("d_ago", n(day))
            else -> date(ts)
        }
    }

    fun date(ts: Long): String {
        if (ts <= 0L) return this["unknown"]
        val c = java.util.Calendar.getInstance().apply { timeInMillis = ts }
        val y = c.get(java.util.Calendar.YEAR)
        val m = c.get(java.util.Calendar.MONTH) + 1
        val d = c.get(java.util.Calendar.DAY_OF_MONTH)
        return digits(y.toString() + "/" + "%02d".format(m) + "/" + "%02d".format(d))
    }

    companion object {
        internal val FA_DIGITS = charArrayOf('۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹')
    }
}

val LocalLoc = compositionLocalOf { Loc("fa") }

const val LANG_FA = "fa"
const val LANG_TR = "tr"
const val LANG_EN = "en"
const val LANG_AR = "ar"

val SUPPORTED_LANGS = listOf(LANG_FA, LANG_TR, LANG_EN, LANG_AR)

fun langLabel(code: String): String = when (code) {
    LANG_TR -> "Türkçe"
    LANG_EN -> "English"
    LANG_AR -> "العربية"
    else -> "فارسی"
}

fun langFlag(code: String): String = when (code) {
    LANG_TR -> "🇹🇷"
    LANG_EN -> "🇬🇧"
    LANG_AR -> "🇸🇦"
    else -> "🇮🇷"
}

